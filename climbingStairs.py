# Problem Statement: Climbing Stairs

# Alice has a staircase with N steps and wants to reach the top. In each move, she can climb either:

# 1 step, or
# M steps

# Your task is to determine the minimum number of moves required for Alice to reach exactly the Nth step.

# Input Format

# The input consists of a single line containing two space-separated integers:

# N M

# Output Format

# Print the minimum number of moves required to reach exactly the Nth step.

# Constraints
# 1 ≤ N, M ≤ 10⁹

# Example:

# Input:
# 10 3

# Output:
# 4

n,m=map(int,input().split())
print(n,m)